def validate_args(args: argparse.Namespace) -> None:
    if args.quick:
        args.warmups = 1
        args.repetitions = 3
        args.nx = min(args.nx, 32)
        args.nz = min(args.nz, 48)
        args.samples = max(args.samples, 1536)
    if args.warmups < 1 or args.repetitions < 1:
        raise ValueError("Warm-ups and repetitions must be positive.")
    if args.angles < 3 or args.angles % 2 == 0:
        raise ValueError(
            "Use an odd angle count so that broadside can receive zero weight."
        )
    if args.elements < 2 or args.elements % 2:
        raise ValueError("The receive-null aperture requires an even element count.")
    if args.samples < 8 or args.nx < 2 or args.nz < 2:
        raise ValueError("The IQ and image-grid dimensions are too small.")
    if args.angle_span_deg <= 0.0:
        raise ValueError("The total angular span must be positive.")
    if args.pitch_mm <= 0.0 or args.sampling_frequency_mhz <= 0.0:
        raise ValueError("Pitch and sampling frequency must be positive.")
    if args.sound_speed_m_s <= 0.0 or args.dc_offset <= 0.0:
        raise ValueError("Sound speed and DC offset must be positive.")
    if (
        args.validation_max_error_fraction <= 0.0
        or args.validation_p99_error_fraction <= 0.0
        or args.validation_l2_error_fraction <= 0.0
    ):
        raise ValueError("Every numerical-validation tolerance must be positive.")
    if not args.x_min_mm < args.x_max_mm or not args.z_min_mm < args.z_max_mm:
        raise ValueError("Grid limits must be strictly increasing.")


def version_or_none(distribution_names: tuple[str, ...]) -> str | None:
    for name in distribution_names:
        try:
            return importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            continue
    return None


def gpu_properties(cp: Any) -> dict[str, Any]:
    device_id = int(cp.cuda.runtime.getDevice())
    properties = cp.cuda.runtime.getDeviceProperties(device_id)

    def decode(value: Any) -> Any:
        if isinstance(value, bytes):
            return value.decode("utf-8", errors="replace").rstrip("\x00")
        if isinstance(value, np.generic):
            return value.item()
        return value

    selected = {
        key: decode(properties[key])
        for key in (
            "name",
            "totalGlobalMem",
            "major",
            "minor",
            "multiProcessorCount",
        )
        if key in properties
    }
    selected["device_id_within_visible_set"] = device_id
    selected["cuda_driver_version"] = int(cp.cuda.runtime.driverGetVersion())
    selected["cuda_runtime_version"] = int(cp.cuda.runtime.runtimeGetVersion())
    return selected


def cpu_model() -> str | None:
    try:
        with Path("/proc/cpuinfo").open("r", encoding="utf-8") as stream:
            for line in stream:
                if line.lower().startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    value = platform.processor().strip()
    return value or None


def json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.ndarray):
        return [json_safe(item) for item in value.tolist()]
    if isinstance(value, np.generic):
        return json_safe(value.item())
    if isinstance(value, float) and not np.isfinite(value):
        return None
    return value


def make_angles(count: int, total_span_deg: float) -> np.ndarray:
    angles = np.linspace(-0.5 * total_span_deg, 0.5 * total_span_deg, count)
    if not np.allclose(angles, -angles[::-1], rtol=0.0, atol=1e-12):
        raise RuntimeError("The steering-angle set is not symmetric.")
    if not np.isclose(angles[count // 2], 0.0, atol=1e-12):
        raise RuntimeError("The steering-angle set does not contain broadside.")
    return angles.astype(np.float32)


def load_or_generate_iq(
    args: argparse.Namespace, angles_deg: np.ndarray
) -> tuple[np.ndarray, dict[str, Any]]:
    if args.iq_npz is None:
        rng = np.random.default_rng(args.seed)
        shape = (angles_deg.size, args.samples, args.elements)
        iq = (
            rng.standard_normal(shape, dtype=np.float32)
            + 1j * rng.standard_normal(shape, dtype=np.float32)
        ).astype(np.complex64)
        return iq, {
            "kind": "deterministic random complex IQ",
            "seed": int(args.seed),
            "content_used_for_accuracy_claims": False,
        }

    source_path = args.iq_npz.expanduser().resolve()
    if not source_path.is_file():
        raise FileNotFoundError(source_path)
    with np.load(source_path, allow_pickle=False) as archive:
        if args.iq_key not in archive:
            raise KeyError(
                f"NPZ does not contain IQ key {args.iq_key!r}: {source_path}"
            )
        iq = np.asarray(archive[args.iq_key])
        supplied_angles = (
            np.asarray(archive["angles_deg"], dtype=float).reshape(-1)
            if "angles_deg" in archive
            else None
        )
    if iq.ndim != 3:
        raise ValueError("The IQ array must be three-dimensional.")
    if iq.shape[0] != angles_deg.size:
        raise ValueError(
            f"IQ has {iq.shape[0]} angles but --angles is {angles_deg.size}."
        )
    if iq.shape[2] == args.elements:
        canonical = iq
    elif iq.shape[1] == args.elements:
        canonical = iq.transpose(0, 2, 1)
    else:
        raise ValueError(
            "Neither non-angle IQ dimension matches --elements. Expected "
            "(angles, samples, elements) or (angles, elements, samples)."
        )
    if supplied_angles is not None and not np.allclose(
        supplied_angles, angles_deg, rtol=0.0, atol=1e-6
    ):
        raise ValueError("The NPZ angle vector differs from the requested angles.")
    canonical = np.ascontiguousarray(canonical.astype(np.complex64, copy=False))
    args.samples = int(canonical.shape[1])
    return canonical, {
        "kind": "user-supplied NPZ IQ",
        "path": str(source_path),
        "key": args.iq_key,
        "angles_vector_verified": supplied_angles is not None,
    }


def input_transfer_enabled(mode: str) -> bool:
    return mode in ("input", "both")


def output_transfer_enabled(mode: str) -> bool:
    return mode in ("output", "both")


def build_geometry(
    args: argparse.Namespace,
    angles_deg: np.ndarray,
    cp: Any,
    wavefront: Any,
    linear_probe_positions: Callable[..., np.ndarray],
    scan_grid: Callable[..., np.ndarray],
) -> dict[str, Any]:
    x_axis = np.linspace(args.x_min_mm, args.x_max_mm, args.nx) * 1e-3
    z_axis = np.linspace(args.z_min_mm, args.z_max_mm, args.nz) * 1e-3
    grid_points = np.asarray(
        scan_grid(x_axis, np.array([0.0]), z_axis), dtype=np.float32
    )
    receive_coordinates = np.asarray(
        linear_probe_positions(args.elements, args.pitch_mm * 1e-3),
        dtype=np.float32,
    )
    scan_gpu = cp.asarray(grid_points, dtype=cp.float32)
    receive_gpu = cp.asarray(receive_coordinates, dtype=cp.float32)
    arrivals_gpu = []
    for angle_deg in angles_deg:
        angle_rad = np.deg2rad(float(angle_deg))
        direction = np.asarray(
            [np.sin(angle_rad), 0.0, np.cos(angle_rad)], dtype=np.float32
        )
        arrivals = (
            wavefront.plane(
                origin_m=np.zeros(3, dtype=np.float32),
                points_m=grid_points,
                direction=direction,
            )
            / args.sound_speed_m_s
        )
        arrivals_gpu.append(cp.asarray(arrivals, dtype=cp.float32))
    return {
        "x_axis": x_axis,
        "z_axis": z_axis,
        "grid_shape": (args.nx, args.nz),
        "grid_points": grid_points,
        "scan_gpu": scan_gpu,
        "receive_gpu": receive_gpu,
        "arrivals_gpu": arrivals_gpu,
    }


def prepare_channel_data(
    iq_host: np.ndarray, args: argparse.Namespace, cp: Any
) -> dict[str, Any]:
    receive_null = np.ones(args.elements, dtype=np.float32)
    receive_null[: args.elements // 2] = -1.0
    uniform_host = [
        np.ascontiguousarray(iq_angle.T[:, :, None]) for iq_angle in iq_host
    ]
    receive_pair_host = [
        np.ascontiguousarray(
            np.stack([iq_angle, iq_angle * receive_null], axis=-1).transpose(
                1, 0, 2
            )
        )
        for iq_angle in iq_host
    ]
    naive_host = (
        [
            np.ascontiguousarray(
                np.stack(
                    [
                        iq_angle * receive_null,
                        iq_angle * (receive_null + args.dc_offset),
                        iq_angle * (-receive_null + args.dc_offset),
                    ],
                    axis=-1,
                ).transpose(1, 0, 2)
            )
            for iq_angle in iq_host
        ]
        if args.include_naive_reference
        else None
    )
    if input_transfer_enabled(args.transfers):
        uniform_gpu = receive_pair_gpu = naive_gpu = None
    else:
        uniform_gpu = [cp.asarray(item) for item in uniform_host]
        receive_pair_gpu = [cp.asarray(item) for item in receive_pair_host]
        naive_gpu = (
            [cp.asarray(item) for item in naive_host]
            if args.include_naive_reference
            else None
        )
    return {
        "uniform_host": uniform_host,
        "receive_pair_host": receive_pair_host,
        "naive_host": naive_host,
        "uniform_gpu": uniform_gpu,
        "receive_pair_gpu": receive_pair_gpu,
        "naive_gpu": naive_gpu,
    }


def channel_for_angle(
    prepared: dict[str, Any], kind: str, index: int, args: argparse.Namespace, cp: Any
) -> Any:
    host_key = f"{kind}_host"
    gpu_key = f"{kind}_gpu"
    if input_transfer_enabled(args.transfers):
        return cp.asarray(prepared[host_key][index])
    return prepared[gpu_key][index]


def nsi_envelope(cp: Any, uniform: Any, null: Any, dc_offset: float) -> Any:
    plus = null + dc_offset * uniform
    minus = -null + dc_offset * uniform
    return cp.maximum(
        0.5 * (cp.abs(plus) + cp.abs(minus)) - cp.abs(null), 0.0
    )


def output_difference_metrics(
    first: np.ndarray, second: np.ndarray
) -> dict[str, float | bool]:
    """Return scale-aware discrepancy measures for two real output images.

    The conversion to float64 is only for the diagnostic reductions.  It does
    not alter the benchmarked complex64 reconstruction paths.
    """

    first_array = np.asarray(first)
    second_array = np.asarray(second)
    if first_array.shape != second_array.shape:
        raise ValueError(
            "Validation images have different shapes: "
            f"{first_array.shape} versus {second_array.shape}."
        )
    if not np.all(np.isfinite(first_array)) or not np.all(
        np.isfinite(second_array)
    ):
        raise ValueError("Validation images must contain only finite values.")

    first_64 = first_array.astype(np.float64, copy=False)
    second_64 = second_array.astype(np.float64, copy=False)
    difference = np.abs(first_64 - second_64)
    tiny = np.finfo(np.float64).tiny
    peak_scale = max(
        float(np.max(np.abs(first_64))),
        float(np.max(np.abs(second_64))),
        tiny,
    )
    l2_scale = max(
        float(np.linalg.norm(first_64.ravel())),
        float(np.linalg.norm(second_64.ravel())),
        tiny,
    )
    max_absolute = float(np.max(difference))
    p99_absolute = float(np.percentile(difference, 99.0))
    l2_absolute = float(np.linalg.norm(difference.ravel()))
    return {
        "max_absolute_difference": max_absolute,
        "p99_absolute_difference": p99_absolute,
        "l2_absolute_difference": l2_absolute,
        "peak_scale": peak_scale,
        "l2_scale": l2_scale,
        "max_error_fraction_of_peak": float(max_absolute / peak_scale),
        "p99_error_fraction_of_peak": float(p99_absolute / peak_scale),
        "relative_l2_error": float(l2_absolute / l2_scale),
        "exactly_equal": bool(np.array_equal(first_array, second_array)),
    }


def validation_passes(
    metrics: dict[str, float | bool], args: argparse.Namespace
) -> bool:
    return bool(
        float(metrics["max_error_fraction_of_peak"])
        <= args.validation_max_error_fraction
        and float(metrics["p99_error_fraction_of_peak"])
        <= args.validation_p99_error_fraction
        and float(metrics["relative_l2_error"])
        <= args.validation_l2_error_fraction
    )


def validation_report(
    label: str,
    first: np.ndarray,
    second: np.ndarray,
    args: argparse.Namespace,
) -> dict[str, Any]:
    metrics = output_difference_metrics(first, second)
    accepted = validation_passes(metrics, args)
    report: dict[str, Any] = {
        **metrics,
        "accepted": accepted,
        "tolerances": {
            "max_error_fraction_of_peak": args.validation_max_error_fraction,
            "p99_error_fraction_of_peak": args.validation_p99_error_fraction,
            "relative_l2_error": args.validation_l2_error_fraction,
        },
        "interpretation": (
            "Accepted as numerically equivalent for this complex64 benchmark."
            if accepted
            else "Difference exceeds the declared complex64 benchmark tolerance."
        ),
    }
    print(
        f"Numerical validation ({label}): "
        f"max/peak={metrics['max_error_fraction_of_peak']:.3e}, "
        f"p99/peak={metrics['p99_error_fraction_of_peak']:.3e}, "
        f"relative L2={metrics['relative_l2_error']:.3e}, "
        f"accepted={accepted}"
    )
    return report


def execute_method(
    method: str,
    args: argparse.Namespace,
    angles_deg: np.ndarray,
    angular_weights_gpu: Any,
    prepared_channels: dict[str, Any],
    precomputed_geometry: dict[str, Any] | None,
    cp: Any,
    beamform: Callable[..., Any],
    geometry_builder: Callable[[], dict[str, Any]],
) -> Any:
    geometry = (
        precomputed_geometry
        if precomputed_geometry is not None
        else geometry_builder()
    )
    shape = geometry["grid_shape"]
    uniform_sum = cp.zeros(shape, dtype=cp.complex64)

    if method == METHOD_RECEIVE:
        receive_null_sum = cp.zeros(shape, dtype=cp.complex64)
        for index in range(angles_deg.size):
            result = beamform(
                channel_data=channel_for_angle(
                    prepared_channels, "receive_pair", index, args, cp
                ),
                rx_coords_m=geometry["receive_gpu"],
                scan_coords_m=geometry["scan_gpu"],
                tx_wave_arrivals_s=geometry["arrivals_gpu"][index],
                f_number=args.f_number,
                rx_start_s=args.rx_start_us * 1e-6,
                sampling_freq_hz=args.sampling_frequency_mhz * 1e6,
                sound_speed_m_s=args.sound_speed_m_s,
                modulation_freq_hz=args.centre_frequency_mhz * 1e6,
                tukey_alpha=0.0,
            )
            uniform_sum += result[:, 0].reshape(shape)
            receive_null_sum += result[:, 1].reshape(shape)
        envelope = nsi_envelope(
            cp, uniform_sum, receive_null_sum, args.dc_offset
        )

    elif method == METHOD_NAIVE:
        zero_sum = cp.zeros(shape, dtype=cp.complex64)
        plus_sum = cp.zeros(shape, dtype=cp.complex64)
        minus_sum = cp.zeros(shape, dtype=cp.complex64)
        for index in range(angles_deg.size):
            result = beamform(
                channel_data=channel_for_angle(
                    prepared_channels, "naive", index, args, cp
                ),
                rx_coords_m=geometry["receive_gpu"],
                scan_coords_m=geometry["scan_gpu"],
                tx_wave_arrivals_s=geometry["arrivals_gpu"][index],
                f_number=args.f_number,
                rx_start_s=args.rx_start_us * 1e-6,
                sampling_freq_hz=args.sampling_frequency_mhz * 1e6,
                sound_speed_m_s=args.sound_speed_m_s,
                modulation_freq_hz=args.centre_frequency_mhz * 1e6,
                tukey_alpha=0.0,
            )
            zero_sum += result[:, 0].reshape(shape)
            plus_sum += result[:, 1].reshape(shape)
            minus_sum += result[:, 2].reshape(shape)
        envelope = cp.maximum(
            0.5 * (cp.abs(plus_sum) + cp.abs(minus_sum)) - cp.abs(zero_sum),
            0.0,
        )

    elif method in (METHOD_ANGLE_STREAM, METHOD_ANGLE_STORED, METHOD_DAS):
        if method == METHOD_ANGLE_STREAM:
            angular_null_sum = cp.zeros(shape, dtype=cp.complex64)
            angle_stack = None
        elif method == METHOD_ANGLE_STORED:
            angle_stack = cp.empty(
                (*shape, angles_deg.size), dtype=cp.complex64
            )
            angular_null_sum = None
        else:
            angle_stack = angular_null_sum = None

        for index in range(angles_deg.size):
            result = beamform(
                channel_data=channel_for_angle(
                    prepared_channels, "uniform", index, args, cp
                ),
                rx_coords_m=geometry["receive_gpu"],
                scan_coords_m=geometry["scan_gpu"],
                tx_wave_arrivals_s=geometry["arrivals_gpu"][index],
                f_number=args.f_number,
                rx_start_s=args.rx_start_us * 1e-6,
                sampling_freq_hz=args.sampling_frequency_mhz * 1e6,
                sound_speed_m_s=args.sound_speed_m_s,
                modulation_freq_hz=args.centre_frequency_mhz * 1e6,
                tukey_alpha=0.0,
            )
            image = result[:, 0].reshape(shape)
            if method == METHOD_ANGLE_STORED:
                angle_stack[:, :, index] = image
            else:
                uniform_sum += image
                if method == METHOD_ANGLE_STREAM:
                    angular_null_sum += angular_weights_gpu[index] * image

        if method == METHOD_ANGLE_STORED:
            uniform_sum = cp.sum(angle_stack, axis=2)
            angular_null_sum = cp.sum(
                angle_stack * angular_weights_gpu.reshape(1, 1, -1), axis=2
            )

        envelope = (
            cp.abs(uniform_sum)
            if method == METHOD_DAS
            else nsi_envelope(
                cp, uniform_sum, angular_null_sum, args.dc_offset
            )
        )
    else:
        raise KeyError(method)

    if output_transfer_enabled(args.transfers):
        return cp.asnumpy(envelope)
    return envelope


def summarize_times(method: str, times_s: list[float]) -> dict[str, Any]:
    values = np.asarray(times_s, dtype=float)
    q1, median, q3 = np.percentile(values, [25.0, 50.0, 75.0])
    return {
        "method": method,
        "n": int(values.size),
        "median_ms": float(median * 1e3),
        "q1_ms": float(q1 * 1e3),
        "q3_ms": float(q3 * 1e3),
        "iqr_ms": float((q3 - q1) * 1e3),
        "mean_ms": float(np.mean(values) * 1e3),
        "sample_sd_ms": float(np.std(values, ddof=1) * 1e3)
        if values.size > 1
        else 0.0,
        "minimum_ms": float(np.min(values) * 1e3),
        "maximum_ms": float(np.max(values) * 1e3),
    }


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        raise ValueError(f"No rows supplied for {path.name}")
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def verify_file(path: Path) -> None:
    if not path.is_file() or path.stat().st_size == 0:
        raise OSError(f"Output was not written correctly: {path}")
    print(f"Saved: {path.resolve()}")


def plot_summary(path: Path, summaries: list[dict[str, Any]]) -> None:
    labels = [row["method"] for row in summaries]
    medians = np.asarray([row["median_ms"] for row in summaries])
    q1 = np.asarray([row["q1_ms"] for row in summaries])
    q3 = np.asarray([row["q3_ms"] for row in summaries])
    colors = [METHOD_STYLES[label][0] for label in labels]
    markers = [METHOD_STYLES[label][1] for label in labels]

    figure, axis = plt.subplots(figsize=(9.5, 5.0), constrained_layout=True)
    positions = np.arange(len(labels))
    axis.bar(
        positions,
        medians,
        color=colors,
        alpha=0.28,
        edgecolor=colors,
        linewidth=1.2,
    )
    for position, median, low, high, color, marker in zip(
        positions, medians, q1, q3, colors, markers
    ):
        axis.errorbar(
            position,
            median,
            yerr=[[median - low], [high - median]],
            color=color,
            marker=marker,
            markersize=7,
            capsize=5,
            linewidth=1.5,
        )
    axis.set_xticks(positions, labels, rotation=18, ha="right")
    axis.set_ylabel("Synchronized reconstruction time [ms]")
    axis.set_title("Median and interquartile range")
    axis.grid(axis="y", alpha=0.25)
    figure.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(figure)


def main() -> None:
    args = parse_args()
    validate_args(args)

    # GPU visibility is fixed before CuPy or mach-beamform is imported.
    os.environ["CUDA_VISIBLE_DEVICES"] = str(args.device)
    try:
        import cupy as cp
        from mach import wavefront
        from mach.io.must import linear_probe_positions, scan_grid
        from mach.kernel import beamform
    except ImportError as error:
        raise SystemExit(
            "benchmark_nsi.py requires CuPy and mach-beamform. "
            f"Import failed: {error}"
        ) from error

    cp.cuda.Device(0).use()
    angles_deg = make_angles(args.angles, args.angle_span_deg)
    angular_weights = np.sign(angles_deg).astype(np.float32)
    if not np.isclose(float(np.sum(angular_weights)), 0.0, atol=1e-7):
        raise RuntimeError("Angular-null weights do not sum to zero.")
    if angular_weights[angles_deg.size // 2] != 0.0:
        raise RuntimeError("Broadside must have zero angular weight.")
    angular_weights_gpu = cp.asarray(angular_weights)

    iq_host, data_source = load_or_generate_iq(args, angles_deg)
    prepared_channels = prepare_channel_data(iq_host, args, cp)

    def geometry_builder() -> dict[str, Any]:
        return build_geometry(
            args,
            angles_deg,
            cp,
            wavefront,
            linear_probe_positions,
            scan_grid,
        )

    precomputed_geometry = (
        geometry_builder() if args.scope == "kernel" else None
    )

    methods = [METHOD_DAS, METHOD_RECEIVE]
    if args.angle_storage_mode in ("streaming", "both"):
        methods.append(METHOD_ANGLE_STREAM)
    if args.angle_storage_mode in ("stored", "both"):
        methods.append(METHOD_ANGLE_STORED)
    if args.include_naive_reference:
        methods.append(METHOD_NAIVE)

    def run(method: str) -> Any:
        return execute_method(
            method,
            args,
            angles_deg,
            angular_weights_gpu,
            prepared_channels,
            precomputed_geometry,
            cp,
            beamform,
            geometry_builder,
        )

    print(
        f"Benchmarking {len(methods)} methods with {args.warmups} warm-ups "
        f"and {args.repetitions} synchronized repetitions."
    )
    validation_outputs: dict[str, np.ndarray] = {}
    for method in methods:
        for _ in range(args.warmups):
            cp.cuda.Stream.null.synchronize()
            result = run(method)
            cp.cuda.Stream.null.synchronize()
        result_array = (
            np.asarray(result)
            if isinstance(result, np.ndarray)
            else cp.asnumpy(result)
        )
        if result_array.shape != (args.nx, args.nz):
            raise RuntimeError(
                f"Unexpected output shape for {method}: {result_array.shape}"
            )
        if not np.all(np.isfinite(result_array)):
            raise RuntimeError(f"Non-finite output produced by {method}.")
        validation_outputs[method] = result_array.copy()

    numerical_checks: dict[str, Any] = {}
    if (
        METHOD_ANGLE_STREAM in validation_outputs
        and METHOD_ANGLE_STORED in validation_outputs
    ):
        stream = validation_outputs[METHOD_ANGLE_STREAM]
        stored = validation_outputs[METHOD_ANGLE_STORED]
        report = validation_report(
            "streaming versus stored angular NSI", stream, stored, args
        )
        numerical_checks["streaming_vs_stored_angular_nsi"] = report
        if not report["accepted"]:
            raise RuntimeError(
                "Streaming and stored angular NSI differ materially: "
                f"max/peak={report['max_error_fraction_of_peak']:.3e}, "
                f"p99/peak={report['p99_error_fraction_of_peak']:.3e}, "
                f"relative L2={report['relative_l2_error']:.3e}. "
                "These values were printed before the timed repetitions."
            )
    if METHOD_NAIVE in validation_outputs:
        optimized = validation_outputs[METHOD_RECEIVE]
        naive = validation_outputs[METHOD_NAIVE]
        report = validation_report(
            "two-field versus naive conventional NSI", optimized, naive, args
        )
        numerical_checks["two_field_vs_naive_conventional_nsi"] = report
        if not report["accepted"]:
            raise RuntimeError(
                "Two-field and naive conventional NSI differ materially: "
                f"max/peak={report['max_error_fraction_of_peak']:.3e}, "
                f"p99/peak={report['p99_error_fraction_of_peak']:.3e}, "
                f"relative L2={report['relative_l2_error']:.3e}."
            )

    randomizer = random.Random(args.seed)
    raw_rows: list[dict[str, Any]] = []
    times_by_method: dict[str, list[float]] = {method: [] for method in methods}
    for repetition in range(1, args.repetitions + 1):
        execution_order = methods.copy()
        randomizer.shuffle(execution_order)
        for order_index, method in enumerate(execution_order, start=1):
            cp.cuda.Stream.null.synchronize()
            start = time.perf_counter()
            result = run(method)
            cp.cuda.Stream.null.synchronize()
            elapsed = time.perf_counter() - start
            times_by_method[method].append(float(elapsed))
            raw_rows.append(
                {
                    "repetition": repetition,
                    "order_within_repetition": order_index,
                    "method": method,
                    "elapsed_seconds": float(elapsed),
                    "elapsed_milliseconds": float(elapsed * 1e3),
                }
            )
            del result
        print(f"Completed synchronized repetition {repetition}/{args.repetitions}")

    summaries = [
        summarize_times(method, times_by_method[method]) for method in methods
    ]
    das_median = summaries[0]["median_ms"]
    das_mean = summaries[0]["mean_ms"]
    for row in summaries:
        row["ratio_to_das_median"] = float(row["median_ms"] / das_median)
        row["das_over_method_median"] = float(das_median / row["median_ms"])
        row["ratio_to_das_mean"] = float(row["mean_ms"] / das_mean)
        row["das_over_method_mean"] = float(das_mean / row["mean_ms"])

    output_dir = args.output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    runs_path = output_dir / "nsi_timing_runs.csv"
    summary_csv_path = output_dir / "nsi_timing_summary.csv"
    summary_json_path = output_dir / "nsi_timing_summary.json"
    figure_path = output_dir / "nsi_timing_summary.png"
    write_csv(runs_path, raw_rows)
    write_csv(summary_csv_path, summaries)
    plot_summary(figure_path, summaries)

    publication_ready = bool(
        args.warmups >= 10 and args.repetitions >= 50 and not args.quick
    )
    metadata = {
        "benchmark_version": "2",
        "publication_ready_minimum_repetition_check": publication_ready,
        "warning": None
        if publication_ready
        else (
            "This short run does not meet the report's minimum of 10 warm-ups "
            "and 50 synchronized repetitions."
        ),
        "timing_definition": (
            "Wall-clock time bracketed by default-stream CUDA synchronization"
        ),
        "scope": args.scope,
        "included_transfers": {
            "channel_host_to_device": input_transfer_enabled(args.transfers),
            "final_image_device_to_host": output_transfer_enabled(args.transfers),
            "scan_grid_and_transmit_arrivals": args.scope == "reconstruction",
        },
        "excluded_common_steps": [
            "RF acquisition or simulation",
            "RF-to-IQ demodulation",
            "disk input/output",
            "display and figure generation",
        ],
        "angle_image_storage": args.angle_storage_mode,
        "host_buffer_preparation": (
            "Uniform, receive-apodized and optional naive host buffers are "
            "prepared once before timing; selected host-to-device transfers "
            "are included according to --transfers."
        ),
        "receive_nsi_implementation": (
            "one beamformer call per angle with simultaneous U and Z_e outputs"
        ),
        "naive_three_field_reference_included": bool(
            args.include_naive_reference
        ),
        "precision": {
            "channel_data": "complex64",
            "coordinates_and_arrivals": "float32",
            "accumulators": "complex64",
        },
        "numerical_validation_definition": {
            "reason_for_scale_aware_check": (
                "Streaming accumulation and stored-stack reduction use "
                "different complex64 summation orders; the NSI envelope is "
                "cancellation-sensitive."
            ),
            "max_error_fraction_of_peak_tolerance": (
                args.validation_max_error_fraction
            ),
            "p99_error_fraction_of_peak_tolerance": (
                args.validation_p99_error_fraction
            ),
            "relative_l2_error_tolerance": (
                args.validation_l2_error_fraction
            ),
        },
        "data_source": data_source,
        "configuration": {
            "warmups": args.warmups,
            "repetitions": args.repetitions,
            "randomized_interleaving_seed": args.seed,
            "image_grid": {
                "nx": args.nx,
                "nz": args.nz,
                "x_limits_mm": [args.x_min_mm, args.x_max_mm],
                "z_limits_mm": [args.z_min_mm, args.z_max_mm],
            },
            "receive_elements": args.elements,
            "receive_pitch_mm": args.pitch_mm,
            "iq_samples": args.samples,
            "angles_deg": [float(value) for value in angles_deg],
            "angle_count": int(angles_deg.size),
            "total_angle_span_deg": args.angle_span_deg,
            "broadside_angular_weight": float(
                angular_weights[angles_deg.size // 2]
            ),
            "angular_weight_sum": float(np.sum(angular_weights)),
            "f_number": args.f_number,
            "dc_offset": args.dc_offset,
            "centre_frequency_mhz": args.centre_frequency_mhz,
            "sampling_frequency_mhz": args.sampling_frequency_mhz,
            "sound_speed_m_s": args.sound_speed_m_s,
            "rx_start_us": args.rx_start_us,
        },
        "hardware": {
            "requested_cuda_visible_devices": str(args.device),
            "gpu": gpu_properties(cp),
            "cpu": cpu_model(),
            "machine": platform.machine(),
            "platform": platform.platform(),
        },
        "software": {
            "python": sys.version.split()[0],
            "numpy": np.__version__,
            "cupy": cp.__version__,
            "matplotlib": matplotlib.__version__,
            "mach_beamform": version_or_none(("mach-beamform", "mach")),
        },
        "summary": summaries,
        "numerical_checks": numerical_checks,
        "method_order": methods,
        "output_files": {
            "raw_runs_csv": runs_path.name,
            "summary_csv": summary_csv_path.name,
            "summary_figure": figure_path.name,
        },
    }
    with summary_json_path.open("w", encoding="utf-8") as stream:
        json.dump(json_safe(metadata), stream, indent=2, allow_nan=False)
        stream.write("\n")

    for path in (runs_path, summary_csv_path, summary_json_path, figure_path):
        verify_file(path)

    print("\nMedian [IQR] synchronized reconstruction times:")
    for row in summaries:
        print(
            f"  {row['method']}: {row['median_ms']:.3f} ms "
            f"[{row['q1_ms']:.3f}, {row['q3_ms']:.3f}]"
        )
    if not publication_ready:
        print("WARNING: short run; do not cite these timings in the manuscript.")


if __name__ == "__main__":
    main()
