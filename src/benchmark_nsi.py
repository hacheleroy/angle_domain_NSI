#!/usr/bin/env python3
"""Fair synchronized timing benchmark for DAS and two NSI implementations.

This script addresses item 4 of ``PMB_Angular_NSI_revision_report``.  It
benchmarks exactly the independent fields required by each reconstruction:

* DAS: one uniformly apodized field, coherently compounded over angles
* receive-domain NSI: the uniform field ``U`` and receive-null field ``Z_e``
* angle-domain NSI: the uniform field ``U`` and angle-null field ``Z_theta``

The receive-domain implementation requests two beamformer outputs in one call
per angle.  It does *not* make three independent receive beamforming calls.
Angular NSI can be timed either by accumulating ``U`` and ``Z_theta``
while streaming the per-angle images, or by retaining the complete angle
stack.  An explicitly labelled naive three-field receive reference is
available only through ``--include-naive-reference``.

Version 2 replaces the overly strict pixelwise ``allclose`` gate from version
1.  Streaming accumulation and a stored-stack reduction do not use the same
floating-point summation order, and separately launched GPU beamformers can
also show small run-to-run differences.  The benchmark now records the
peak-normalized maximum, 99th-percentile and relative-L2 discrepancies.  It
accepts only discrepancies below explicit, configurable complex64 tolerances
and reports the measured values if the validation fails.

Timing uses wall-clock measurements bracketed by CUDA synchronization.  The
default publication run uses 10 warm-ups and 50 interleaved repetitions.
Random complex IQ data are generated by default because beamformer execution
time does not depend on image content.  A real IQ stack can instead be supplied
as an NPZ array with shape (angles, samples, elements) or
(angles, elements, samples).

Outputs
-------
``nsi_timing_runs.csv``
    One row per synchronized repetition
``nsi_timing_summary.csv``
    Median, quartiles, IQR, mean and sample standard deviation
``nsi_timing_summary.json``
    Results plus complete hardware, software and scope metadata
``nsi_timing_summary.png``
    Median time with the interquartile range

Required packages: NumPy, Matplotlib, CuPy and mach-beamform.
"""

