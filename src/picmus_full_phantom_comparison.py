#!/usr/bin/env python3
"""Six-method full-field PICMUS resolution-phantom comparison.

This analysis provides manuscript Figure 2.  It reconstructs one common field
containing every point target and supplements the overview with a quantitative
central-to-local-peak diagnostic derived from the directly beamformed fine
lateral profiles generated by :mod:`picmus_experimental_psf`.  MV and DMAS are
evaluated on method-appropriate native grids and resampled only for the common
display; the quantitative profiles are never measured from those resampled
maps.
"""

